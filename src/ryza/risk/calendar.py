def is_business_day(d: date) -> bool:
    """JP 営業日か(土日でない かつ 祝日テーブルに無い)。

    祝日テーブル(``_JP_HOLIDAYS``)の範囲外は「祝日でない = 営業日」に倒れる。
    G-10 鮮度検査は「経過営業日 > 2 で block」なので、この倒れ方は把握していない
    祝日を営業日として数え、経過をやや**過大評価**する(= より早く block する)。
    ゲートの fail-closed 原則に沿う方向である。
    """
    if d.weekday() >= 5:  # Sat=5, Sun=6
        return False
    return d not in _JP_HOLIDAYS


def business_days_between(start: date, end: date) -> int:
    """半開区間 ``(start, end]`` の営業日数(``start`` は含まず ``end`` は含む)。

    - ``end == start``: 0(同日は経過ゼロ)
    - ``end < start``: 0(将来の as_of は経過なし扱い — 呼び出し側が判定を誤らない
      よう、G-10 側で「as_of が判定時点より未来」を別途 fail-closed で block する)
    - ``end > start``: ``start`` の翌日〜``end`` に含まれる営業日の数

    G-10 は「as_of の営業日数経過 > 2 で block」を判定する。
    """
    if end <= start:
        return 0
    days = 0
    cursor = start + timedelta(days=1)
    while cursor <= end:
        if is_business_day(cursor):
            days += 1
        cursor += timedelta(days=1)
    return days


def to_jst_date(dt: datetime) -> date:
    """``datetime`` を JST(``Asia/Tokyo``)の日付に落とす。

    ``limits_state.as_of`` は timestamptz なので、営業日換算は JST の日付境界で行う
    (基準通貨 JPY・IPS §1 と同じ流儀 — ``gate.orders`` の当日売買代金と揃える)。
    """
    from zoneinfo import ZoneInfo

    return dt.astimezone(ZoneInfo("Asia/Tokyo")).date()


